#!/usr/bin/env python3
"""Regenerate Napplet/Test/UpstreamExamples.lean.

Usage: upstream_examples.py <dir with NAP-<WORD>.md fetched at the README commits>
Every `-> {...}` example (napplet -> shell) that is valid JSON becomes a #guard that
the domain's component decodes it as a recognised request. Examples containing
non-JSON placeholders (NAP-UPLOAD's `<Blob ...>`) are skipped and listed.
"""
import json, re, sys
up = sys.argv[1].rstrip('/') + '/'
names = {"SHELL":"Shell","INTENT":"Intent","INC":"Inc","THEME":"Theme","IDENTITY":"Identity",
 "RELAY":"Relay","STORAGE":"Storage","KEYS":"Keys","MEDIA":"Media","NOTIFY":"Notify",
 "RESOURCE":"Resource","CONFIG":"Config","UPLOAD":"Upload","VALUE":"Value","OUTBOX":"Outbox",
 "CVM":"Cvm","LINK":"Link","POW":"Pow","DISPLAY":"Display"}
out, skipped = [], []
for N, f in names.items():
    lines = open(up + f'NAP-{N}.md').read().split('\n')
    i = 0
    while i < len(lines):
        m = re.match(r'\s*(?:opener |target )?->\s*(\{.*)$', lines[i])
        if not m:
            i += 1; continue
        txt, j, obj = m.group(1), i, None
        while True:
            try:
                obj = json.loads(txt); break
            except Exception:
                j += 1
                if j >= len(lines) or j - i > 60 or re.match(r'\s*(<-|->|```)', lines[j]):
                    obj = None; break
                txt += '\n' + lines[j]
        (out.append((f, json.dumps(obj))) if isinstance(obj, dict) else skipped.append(N))
        i = j + 1
src = ['import Napplet.Runtime', '',
 '/-! Every upstream napplet→shell example request (text after `->` in each NAP spec at the',
 'README commits) decodes as a recognised request of its domain. Generated by',
 '`scripts/upstream_examples.py`. -/', '', 'namespace Napplet.Test.Upstream', '',
 'def ok {α : Type} : Decoded α → Bool', '  | .ok _ => true', '  | _ => false', '']
src += [f'#guard ok (Run.{f}.decode (Json.parse! {json.dumps(t)}))' for f, t in out]
src += ['', 'end Napplet.Test.Upstream', '']
open('Napplet/Test/UpstreamExamples.lean', 'w').write('\n'.join(src))
print(len(out), 'examples; skipped (non-JSON placeholders):', skipped)
